export function isCodexUnlocked(entry: CodexEntry, save: GameSave): boolean {
  if (entry.unlockFromStart) return true;
  if (entry.unlockChapter !== undefined && save.chapter >= entry.unlockChapter) return true;
  if (entry.unlockFlags) {
    for (const f of entry.unlockFlags) {
      if (!save.flags.includes(f)) return false;
    }
    return true;
  }
  if (entry.unlockRelationships) {
    for (const [k, v] of Object.entries(entry.unlockRelationships)) {
      if ((save.relationships[k] ?? 0) < v) return false;
    }
    return true;
  }
  return false;
}



