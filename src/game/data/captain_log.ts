export function unlockedLogEntries(chapter: number, flags: string[]): LogEntry[] {
  return CAPTAIN_LOG.filter((e) => {
    // Flag-gated entries: all flags must be present
    if (e.unlockFlags && e.unlockFlags.length > 0) {
      return e.unlockFlags.every((f) => flags.includes(f));
    }
    // Chapter-gated entries
    if (e.unlockChapter !== undefined && chapter >= e.unlockChapter) return true;
    return false;
  });
}
