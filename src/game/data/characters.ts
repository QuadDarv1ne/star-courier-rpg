export function relationshipStatus(value: number | undefined): string {
  if (value === undefined || value === 0) return "Нейтрально";
  if (value >= 80) return "Доверие";
  if (value >= 50) return "Дружба";
  if (value >= 20) return "Симпатия";
  if (value > -20) return "Нейтрально";
  if (value > -50) return "Холод";
  if (value > -80) return "Неприязнь";
  return "Вражда";
}

