let lastQuoteIdx = -1;

export function quoteOfTheMoment(): { text: string; author: string } {
  // Pick a random character and return their canonical quote with their name
  let idx = Math.floor(Math.random() * CHARACTERS.length);
  // Avoid picking the same character twice in a row
  if (idx === lastQuoteIdx) idx = (idx + 1) % CHARACTERS.length;
  lastQuoteIdx = idx;
  const ch = CHARACTERS[idx];
  return { text: ch.quote, author: ch.name };
}
